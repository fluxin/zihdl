const std = @import("std");
const netlist = @import("js_asic").netlist;
const Signal = netlist.Signal;
const ModuleBuilder = netlist.ModuleBuilder;

/// One cycle of a generated testbench stimulus. The player drives `scl` and the
/// open-drain `sda_low`/`sda_oe` lines and optionally compares sampled inputs.
pub const Vector = struct {
    /// Value presented on the host read-data bus (`host_rdata`).
    host_rdata: u32 = 0,
    scl: u1 = 0,
    /// Master pulls SDA low when `sda_oe` is high.
    sda_low: u1 = 0,
    sda_oe: u1 = 0,
    /// Compare `sda_in` against `sample_expected` this cycle when set.
    sample_valid: u1 = 0,
    sample_expected: u1 = 0,
    /// Compare `raddr_in` against `raddr_expected` this cycle when set.
    raddr_valid: u1 = 0,
    raddr_expected: u8 = 0,

    pub fn pack(self: Vector) u64 {
        var word: u64 = self.host_rdata;
        word |= @as(u64, self.scl) << 32;
        word |= @as(u64, self.sda_low) << 33;
        word |= @as(u64, self.sda_oe) << 34;
        word |= @as(u64, self.sample_valid) << 35;
        word |= @as(u64, self.sample_expected) << 36;
        word |= @as(u64, self.raddr_valid) << 37;
        word |= @as(u64, self.raddr_expected) << 38;
        return word;
    }
};

/// Plays a `depth`-cycle stimulus image generated by the test author and
/// reports any sampled mismatch. The last image word is control data:
/// `[31:0] = cycles`, the number of valid vectors.
pub fn VectorPlayer(comptime init_file: []const u8, comptime depth: usize) type {
    const addr_w = std.math.log2_int_ceil(usize, depth);
    return struct {
        pub const name = "tb_vector_player";
        pub const Inputs = struct {
            clk: Signal(1),
            rst_n: Signal(1),
            sda_in: Signal(1),
            raddr_in: Signal(8),
        };
        pub const Outputs = struct {
            host_rdata: Signal(32),
            scl: Signal(1),
            sda_low: Signal(1),
            sda_oe: Signal(1),
            done: Signal(1),
            fail: Signal(1),
            fail_addr: Signal(addr_w),
        };

        pub fn build(mb: *ModuleBuilder) !void {
            const ins = try mb.declareInputs(Inputs);
            const outs = try mb.declareOutputs(Outputs);
            const b = mb.exprs();

            const stim = try mb.mem(64, "stim", depth, .{ .init_file = init_file });
            const addr = try mb.reg("addr", addr_w, 0);
            const fail_r = try mb.reg("fail_r", 1, 0);
            const fail_addr_r = try mb.reg("fail_addr_r", addr_w, 0);

            const word = b.memRead(stim, addr.expr());
            const control = b.memRead(stim, b.lit(addr_w, depth - 1));
            const cycles = b.trunc(control, 32);

            try mb.assign(outs.host_rdata, b.trunc(word, 32));
            try mb.assign(outs.scl, b.bit(word, 32));
            try mb.assign(outs.sda_low, b.bit(word, 33));
            try mb.assign(outs.sda_oe, b.bit(word, 34));

            const bad_sample = b.and_(b.bit(word, 35), b.ne(ins.sda_in.expr(), b.bit(word, 36)));
            const bad_raddr = b.and_(b.bit(word, 37), b.ne(ins.raddr_in.expr(), b.slice(word, 45, 38)));
            try mb.assign(outs.fail, b.or_(fail_r.expr(), b.or_(bad_sample, bad_raddr)));
            try mb.assign(outs.fail_addr, fail_addr_r.expr());
            try mb.assign(outs.done, b.eq(addr.expr(), b.sub(cycles, 1)));

            const last = b.sub(cycles, 1);
            try mb.seq(.{ .clk = ins.clk, .rst_n = ins.rst_n }, &.{
                b.when(b.or_(bad_sample, bad_raddr), &.{
                    b.when(b.eq(fail_r.expr(), 0), &.{b.assign(fail_addr_r, addr.expr())}, &.{}),
                    b.assign(fail_r, 1),
                }, &.{}),
                b.when(b.lt(addr.expr(), last), &.{b.assign(addr, b.add(addr.expr(), 1))}, &.{}),
            });
        }
    };
}
